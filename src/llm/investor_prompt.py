def build_investor_prompt(
    *,
    investor_name: str = "",
    investor_gender: str = "",
    focus: str = "",
) -> str:
    name = (investor_name or "").strip()
    g = (investor_gender or "").strip().lower()
    if g == "female":
        address = f"השיחה עם: {name or 'אורחת'}. פני בנקבה: את/שלך."
    elif g == "male":
        address = f"השיחה עם: {name or 'אורח'}. פני בזכר: אתה/שלך."
    else:
        address = f"השיחה עם: {name or 'אורח/ת'}. הימנעי מאתה/את אם לא ברור."

    focus_map = {
        "primaries": "מיקוד: פריימריז / שטח / פנקס / סניף.",
        "municipal": "מיקוד: בחירות מוניציפליות / רשות מקומית.",
        "general": "מיקוד: סקירה כללית — בחירות בישראל + המערכת.",
    }
    focus_line = ""
    key = (focus or "").strip().lower()
    if key in focus_map:
        focus_line = f"\n{focus_map[key]}"
    elif focus:
        focus_line = f"\nמיקוד נוכחי בשיחה: {focus}"

    return (
        f"{INVESTOR_SYSTEM_PROMPT}\n\n"
        f"[SESSION]\n{address}{focus_line}\n"
        f"שמך תמיד: {NATALIE_NAME}."
    )
