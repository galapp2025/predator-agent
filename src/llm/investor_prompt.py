def build_investor_prompt(
    *,
    investor_name: str = "",
    investor_gender: str = "",
    focus: str = "",
) -> str:
    name = (investor_name or "").strip()
    g = (investor_gender or "").strip().lower()
    if g == "female":
        address = f"המשקיעה: {name or 'אורחת'}. פני בנקבה: את/שלך."
    elif g == "male":
        address = f"המשקיע: {name or 'אורח'}. פני בזכר: אתה/שלך."
    else:
        address = f"האורח: {name or 'אורח/ת'}. הימנעי מאתה/את אם לא ברור."

    focus_line = ""
    if focus:
        focus_line = f"\nמיקוד נוכחי בשיחה: {focus}"

    return (
        f"{INVESTOR_SYSTEM_PROMPT}\n\n"
        f"[SESSION]\n{address}{focus_line}\n"
        f"שמך תמיד: {NATALIE_NAME}."
    )
